# ---------------------------------------------------------------- frame ring (512 x 512)

def frame_ring():
    c = Canvas(512, 512)
    r = np.hypot(c.x, c.y)
    d = np.abs(r - 225.0) - 21.0
    t = np.clip(0.5 + (c.y * 0.7 - c.x * 0.5) / 520.0, 0.0, 1.0)
    base = lerp(hexrgb("DDE0E6"), hexrgb("FFFFFF"), t)
    c.over(base, fill(d))
    c.over(hexrgb("C4C8D2"), fill(np.abs(r - 205.0) - 1.6) * fill(d) * 0.55)    # the inner edge
    c.over((255, 255, 255), fill(np.abs(r - 243.0) - 1.4) * fill(d) * 0.7)       # the outer lit edge
    return "UI_Frame_Ring", c, RUNTIME_FRAMES


