def glyph_canvas():
    return Canvas(96, 96)


def ink(c, d, color=INK, edge=1.9):
    c.over(hexrgb(CREAM_EDGE), fill(d + edge) * 0.92)
    c.over(hexrgb(color), fill(d))


def cut(c, d, color=CREAM_EDGE, mask=None, alpha=1.0):
    c.over(hexrgb(color), fill(d) * alpha * (1.0 if mask is None else mask))


