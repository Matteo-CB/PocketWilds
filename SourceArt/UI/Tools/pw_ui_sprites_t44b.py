"""Pocket Wilds UI sprites added in T44B (Succes, titres, cadres de profil; doc 01 sections 3 and 4).

Same method as pw_ui_sprites_t44.py (signed distances rendered at 4x, box-filtered down), same family: rounded filled shapes,
one warm outline, light from the top left, a soft drop shadow. Owner rules: round dots, five-point stars (never four points,
never a star inside a circle that touches its points), pearls, hearts and paws; nothing religious or national; handmade only.

- Art/UI/Profile (192 x 192): UI_Badge_Bronze, UI_Badge_Silver, UI_Badge_Gold (soft round medals with a lighter inner disc
  where the category icon sits), UI_Badge_Star (a plump ROUND five-point star, inner star lighter), UI_Badge_Locked.
- Art/UI/Icons: 13 ICO_AchCat_<Category> (96 x 96, dark warm ink with a cream edge: readable over every badge) and
  ICO_Achievement (128 x 128, the HUD button: a gold medal with a cream paw and two ribbon tails).
- Art/UI/Profile/Frames: UI_Frame_Ring (512 x 512 white ring, tinted at run time) and the 96 x 96 motifs M_<Name>. White
  motifs are tinted per slot (see Editor/Profile/FrameArt.cs, generated by this script from FRAMES below); coloured ones
  keep their own colours (tint white).

Run alone (python SourceArt/UI/Tools/pw_ui_sprites_t44b.py) to write the sprites and FrameArt.cs, or through
pw_ui_sprites.py (main) for the sprites.
"""
