def badge_disc(name, top, bottom, outline, inner_top, inner_bottom, inner_line, shade):
    c = Canvas(192, 192, cy=94.0)
    body = sd_circle(c, 86.0, 0.0, 0.0)
    drop_shadow(c, body, dy=4.0, radius=3.5, strength=0.3)
    piece(c, body, top, bottom, outline, 86.0, -86.0, lw=3.4, shade=shade, rim="FFFFFF", gl=(30.0, 11.0, -34.0, 52.0, 38.0))
    for k in range(20):   # a ring of tiny round studs
        a = math.tau * k / 20.0
        dots(c, [(math.cos(a) * 75.5, math.sin(a) * 75.5)], 2.2, shade_of(bottom, 0.25), 0.7)
    inner = sd_circle(c, 62.0, 0.0, 0.0)
    c.over(hexrgb(inner_line), fill(inner))
    c.over(vgrad(c, inner_top, inner_bottom, 62.0, -62.0), fill(inner + 2.6))
    lower_shade(c, inner + 2.6, shade_of(inner_bottom, 0.12), 0.0, 62.0, width=9.0, strength=0.45)
    top_rim(c, inner + 2.6, 30.0, 32.0, 0.5)
    return name, c, RUNTIME_PROFILE


