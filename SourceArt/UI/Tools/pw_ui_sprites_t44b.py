def white_piece(c, d, y=40.0, lw=2.2):
    piece(c, d, WHITE[0], WHITE[1], WHITE[2], y, -y, lw=lw, shade=WHITE[3], rim="FFFFFF")


def flower(c, n, pr, dist, top, bottom, line, heart_r=8.0, heart=("FFE08A", "E8A838")):
    petals = [sd_circle(c, pr, math.cos(math.radians(90.0 + 360.0 * k / n)) * dist, math.sin(math.radians(90.0 + 360.0 * k / n)) * dist) for k in range(n)]
    core = sd_circle(c, heart_r)
    family(c, petals + [core], strength=0.2)
    for p in petals:
        piece(c, p, top, bottom, line, 40.0, -40.0, lw=1.8)
    piece(c, core, heart[0], heart[1], "B97A1E", heart_r, -heart_r, lw=1.6)


