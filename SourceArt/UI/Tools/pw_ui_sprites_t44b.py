def m_water_lily():
    c = mk()
    pad = sd_ellipse(c, 40.0, 22.0, 0.0, -14.0)
    petals = []
    for ang, hw, hl in ((90.0, 9.0, 21.0), (55.0, 8.5, 19.0), (125.0, 8.5, 19.0), (22.0, 8.0, 16.0), (158.0, 8.0, 16.0)):
        a = math.radians(ang)
        v = View(c, math.cos(a) * 15.0, -10.0 + math.sin(a) * 12.0, ang - 90.0)
        petals.append(sd_drop(v, hw, hl, -0.3))
    family(c, [pad] + petals)
    piece(c, pad, "A6E08A", "4F9A58", "2F6E3C", 8.0, -36.0, lw=2.0, shade="3F7A48")
    for p, (t, b) in zip(reversed(petals), reversed([("FFE3EC", "F59CB8")] * 5)):
        piece(c, p, t, b, "B8587A", 28.0, -8.0, lw=1.8)
    dots(c, [(0.0, -9.0)], 4.5, "FFD36A", 1.0)
    return finish("WaterLily", c)


