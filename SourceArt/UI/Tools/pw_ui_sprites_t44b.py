SLOT_CS = {TOP: "Top", BOT: "Bottom", TL: "TopLeft", TR: "TopRight", BL: "BottomLeft", BR: "BottomRight"}


def write_frame_art():
    lines = [CS_HEADER.rstrip("\n")]
    for key, ring, rim, style, count, colours, motifs in FRAMES:
        ms = ", ".join('new FrameMotif("%s", FrameSlot.%s, 0x%s)' % (s, SLOT_CS[slot], t) for s, slot, t in motifs)
        cs = ", ".join("0x" + col for col in colours)
        lines.append('            new FrameArt("%s", 0x%s, 0x%s, FrameRingStyle.%s, %d, new uint[] { %s }, new FrameMotif[] { %s }),'
                     % (key, ring, rim, style.capitalize(), count, cs, ms))
    lines.append("        };\n    }\n}\n")
    os.makedirs(os.path.dirname(FRAME_ART_CS), exist_ok=True)
    with open(FRAME_ART_CS, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", FRAME_ART_CS, len(FRAMES), "frames")


def main():
    for folder in (RUNTIME_ICONS, RUNTIME_PROFILE, RUNTIME_FRAMES, MASTERS):
        os.makedirs(folder, exist_ok=True)
    for build in T44B_SPRITES:
        name, canvas, folder = build()
        canvas.image(True).save(os.path.join(folder, name + ".png"), optimize=True)
        canvas.image(False).save(os.path.join(MASTERS, name + "@4x.png"), optimize=True)
        print("wrote", name, canvas.w, "x", canvas.h)
    write_frame_art()


if __name__ == "__main__":
    main()
