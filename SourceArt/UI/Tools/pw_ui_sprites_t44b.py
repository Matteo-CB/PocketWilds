def moon(name, kind, flip):
    c = mk()
    s = -1.0 if flip else 1.0
    disc = sd_circle(c, 31.0)
    family(c, [disc])
    piece(c, disc, "7E8DB8", "5A6892", "34406E", 31.0, -31.0, lw=2.0)
    cx = c.x * s
    if kind == "full":
        lit = disc
    elif kind == "half":
        lit = np.maximum(disc, -cx)
    elif kind == "gibbous":
        lit = np.maximum(disc, np.minimum(-cx, sd_ellipse(c, 17.0, 32.0)))
    else:   # crescent
        lit = np.maximum(disc, -sd_circle(c, 29.0, -15.0 * s, 0.0))
    piece(c, lit, "FFF8DC", "F0DC9C", "A8965A", 31.0, -31.0, lw=0.01, shade="D9C47E")
    return finish(name, c)


