#nullable enable

namespace PocketWilds.Simulation
{
    /// <summary>The system whose small icon a journal page shows (doc 01 Succès, section 6 « Règles »).</summary>
    public enum JournalSystem : byte
    {
        Refuge = 0,
        Hatch = 1,
        Collection = 2,
        Mastery = 3,
        Biomes = 4,
        Bonds = 5,
        Activities = 6,
        Expeditions = 7,
        Garden = 8,
        Daily = 9,
        Visitors = 10,
        Albums = 11,
        Decoration = 12,
        Breeding = 13,
        Events = 14,
        Renewal = 15,
        Photo = 16,
        Outfit = 17,
        Achievements = 18,
        Circle = 19,
    }

    /// <summary>One moment of the doc's table (JournalMomentDefinition: id, trigger's system, image, repeatable, variables).</summary>
    public readonly struct JournalMomentRow
    {
        /// <summary>memory.first_hatch…; its text is « {Key}.text ».</summary>
        public readonly string Key;

        public readonly JournalSystem System;
        public readonly JournalImageKind Image;

        /// <summary>« (répétable) » in the doc: a page each time (once per subject when the moment has one).</summary>
        public readonly bool Repeatable;

        /// <summary>The variables its text uses, in the order the page keeps their values (two at most).</summary>
        public readonly string[] Variables;

        public JournalMomentRow(string key, JournalSystem system, JournalImageKind image, bool repeatable, string[] variables)
        {
            Key = key;
            System = system;
            Image = image;
            Repeatable = repeatable;
            Variables = variables;
        }

        /// <summary>The image is a capture made at run time (an animal portrait or a refuge view).</summary>
        public bool IsCapture => Image == JournalImageKind.AnimalCapture || Image == JournalImageKind.RefugeCapture;
    }

    /// <summary>The 63 moments (generated by Tools/Data/pw_journal_data.py from the doc's table).</summary>
    public static partial class JournalData
    {
        public static ref readonly JournalMomentRow Row(int moment) => ref Rows[moment];

        /// <summary>The moment's index from its key (−1 when unknown). Allocation-free; not for a per-frame path.</summary>
        public static int IndexOf(string key)
        {
            for (int i = 0; i < Rows.Length; i++)
                if (string.Equals(Rows[i].Key, key, System.StringComparison.Ordinal))
                    return i;
            return -1;
        }
    }
}
